"""Autonomous Agent System - Multi-agent coordination and execution."""

from __future__ import annotations

import asyncio
import logging
import uuid
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any, Callable, Dict, List, Optional

logger = logging.getLogger(__name__)


class AgentStatus(Enum):
    """Agent execution status."""
    IDLE = "idle"
    PLANNING = "planning"
    EXECUTING = "executing"
    WAITING = "waiting"
    COMPLETED = "completed"
    FAILED = "failed"


class AgentCapability(Enum):
    """Agent capabilities."""
    PLANNING = "planning"
    RESEARCH = "research"
    CODING = "coding"
    MEMORY = "memory"
    DESKTOP = "desktop"
    BROWSER = "browser"
    MONITORING = "monitoring"
    REMINDER = "reminder"
    TASK_EXECUTION = "task_execution"


@dataclass
class AgentTask:
    """A task for an agent to execute."""
    id: str
    description: str
    agent_type: str
    priority: int = 5
    context: Dict[str, Any] = field(default_factory=dict)
    dependencies: List[str] = field(default_factory=list)
    status: AgentStatus = AgentStatus.IDLE
    result: Optional[Any] = None
    error: Optional[str] = None
    created_at: float = 0.0
    started_at: float = 0.0
    completed_at: float = 0.0
    
    def __post_init__(self):
        if not self.created_at:
            self.created_at = datetime.now().timestamp()
    
    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "description": self.description,
            "agent_type": self.agent_type,
            "priority": self.priority,
            "context": self.context,
            "dependencies": self.dependencies,
            "status": self.status.value,
            "result": self.result,
            "error": self.error,
            "created_at": self.created_at,
            "started_at": self.started_at,
            "completed_at": self.completed_at,
        }


@dataclass
class AgentPlan:
    """A plan generated by the planner agent."""
    id: str
    goal: str
    steps: List[AgentTask]
    estimated_duration: float = 0.0
    confidence: float = 0.0
    
    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "goal": self.goal,
            "steps": [step.to_dict() for step in self.steps],
            "estimated_duration": self.estimated_duration,
            "confidence": self.confidence,
        }


class BaseAgent(ABC):
    """Base class for all autonomous agents."""
    
    def __init__(self, name: str, capabilities: List[AgentCapability]):
        self.name = name
        self.capabilities = capabilities
        self.status = AgentStatus.IDLE
        self.current_task: Optional[AgentTask] = None
        
    @abstractmethod
    async def execute(self, task: AgentTask) -> Any:
        """Execute a task.
        
        Args:
            task: Task to execute
            
        Returns:
            Task result
        """
        pass
    
    @abstractmethod
    async def plan(self, goal: str, context: Dict[str, Any]) -> AgentPlan:
        """Plan how to achieve a goal.
        
        Args:
            goal: Goal to achieve
            context: Execution context
            
        Returns:
            Execution plan
        """
        pass
    
    def can_handle(self, task: AgentTask) -> bool:
        """Check if this agent can handle a task."""
        return task.agent_type == self.name.lower()


class PlannerAgent(BaseAgent):
    """Agent that plans complex tasks."""
    
    def __init__(self):
        super().__init__("planner", [AgentCapability.PLANNING])
        
    async def execute(self, task: AgentTask) -> Any:
        """Execute a planning task."""
        self.status = AgentStatus.EXECUTING
        self.current_task = task
        
        try:
            plan = await self.plan(task.description, task.context)
            self.status = AgentStatus.COMPLETED
            return plan
        except Exception as e:
            self.status = AgentStatus.FAILED
            task.error = str(e)
            raise
    
    async def plan(self, goal: str, context: Dict[str, Any]) -> AgentPlan:
        """Generate a plan for achieving a goal."""
        # Simple planning - break goal into steps
        plan_id = str(uuid.uuid4())
        
        # Analyze goal to determine required agent types
        agent_types = self._determine_required_agents(goal)
        
        # Create tasks for each agent type
        steps = []
        for i, agent_type in enumerate(agent_types):
            step = AgentTask(
                id=str(uuid.uuid4()),
                description=f"Execute {agent_type} step for: {goal}",
                agent_type=agent_type,
                priority=max(1, 10 - i),
                context=context,
            )
            if i > 0:
                step.dependencies = [steps[i-1].id]
            steps.append(step)
        
        return AgentPlan(
            id=plan_id,
            goal=goal,
            steps=steps,
            estimated_duration=len(steps) * 300,  # 5 min per step
            confidence=0.8,
        )
    
    def _determine_required_agents(self, goal: str) -> List[str]:
        """Determine which agents are needed for a goal."""
        goal_lower = goal.lower()
        
        agents = []
        
        if any(word in goal_lower for word in ["research", "find", "search", "look up"]):
            agents.append("research")
        
        if any(word in goal_lower for word in ["code", "program", "develop", "implement", "fix"]):
            agents.append("coding")
        
        if any(word in goal_lower for word in ["remember", "memory", "store", "recall"]):
            agents.append("memory")
        
        if any(word in goal_lower for word in ["desktop", "window", "application", "file"]):
            agents.append("desktop")
        
        if any(word in goal_lower for word in ["browser", "web", "website", "page"]):
            agents.append("browser")
        
        if not agents:
            agents.append("general")
        
        return agents


