class AgentCoordinator:
    """Coordinates multiple agents for complex tasks."""
    
    def __init__(self):
        self._agents: Dict[str, BaseAgent] = {}
        self._task_queue: List[AgentTask] = []
        self._running = False
        self._execution_task: Optional[asyncio.Task] = None
        
        # Register built-in agents
        self._register_builtin_agents()
    
    def _register_builtin_agents(self) -> None:
        """Register built-in agents."""
        self._agents["planner"] = PlannerAgent()
        self._agents["research"] = ResearchAgent()
        self._agents["coding"] = CodingAgent()
        self._agents["memory"] = MemoryAgent()
        self._agents["desktop"] = DesktopAgent()
        self._agents["browser"] = BrowserAgent()
    
    def register_agent(self, agent: BaseAgent) -> None:
        """Register a custom agent."""
        self._agents[agent.name.lower()] = agent
        logger.info("Registered agent: %s", agent.name)
    
    async def execute_goal(self, goal: str, context: Dict[str, Any]) -> Dict[str, Any]:
        """Execute a goal using agent coordination.
        
        Args:
            goal: Goal to achieve
            context: Execution context
            
        Returns:
            Execution results
        """
        # First, use planner to create a plan
        planner = self._agents["planner"]
        plan = await planner.plan(goal, context)
        
        results = {
            "goal": goal,
            "plan": plan.to_dict(),
            "executions": [],
        }
        
        # Execute plan steps
        for step in plan.steps:
            try:
                # Wait for dependencies
                for dep_id in step.dependencies:
                    # In production, wait for dependency completion
                    pass
                
                # Find appropriate agent
                agent = self._agents.get(step.agent_type)
                if not agent:
                    # Use planner as fallback
                    agent = self._agents["planner"]
                
                # Execute step
                step.status = AgentStatus.EXECUTING
                step.started_at = datetime.now().timestamp()
                
                result = await agent.execute(step)
                
                step.status = AgentStatus.COMPLETED
                step.completed_at = datetime.now().timestamp()
                step.result = result
                
                results["executions"].append({
                    "step_id": step.id,
                    "agent": agent.name,
                    "status": "completed",
                    "result": result,
                })
                
            except Exception as e:
                step.status = AgentStatus.FAILED
                step.error = str(e)
                step.completed_at = datetime.now().timestamp()
                
                results["executions"].append({
                    "step_id": step.id,
                    "agent": agent.name if agent else "unknown",
                    "status": "failed",
                    "error": str(e),
                })
                
                logger.error("Step execution failed: %s", e)
        
        return results
    
    def get_agent(self, name: str) -> Optional[BaseAgent]:
        """Get an agent by name."""
        return self._agents.get(name.lower())
    
    def list_agents(self) -> List[BaseAgent]:
        """List all registered agents."""
        return list(self._agents.values())


_agent_coordinator: Optional[AgentCoordinator] = None


def get_agent_coordinator() -> AgentCoordinator:
    global _agent_coordinator
    if _agent_coordinator is None:
        _agent_coordinator = AgentCoordinator()
    return _agent_coordinator
